#!/usr/bin/env bash
# Write the work_hours ACL and reload squid (spec §5.5). Owner: POL-4.
#   set-worktime.sh [--no-reload] real|always|never
# Portable: bash 3.2/BSD (macOS) and bash 5/GNU (Linux).
set -euo pipefail

cd "$(dirname "$0")/.."

usage() { echo 'usage: set-worktime.sh [--no-reload] real|always|never' >&2; exit 2; }

reload=1
if [ "${1:-}" = "--no-reload" ]; then reload=0; shift; fi
[ "$#" -eq 1 ] || usage
mode=$1
case "$mode" in
  real) acl='acl work_hours time MTWHF 08:00-17:00' ;;
  always) acl='acl work_hours time 00:00-23:59' ;;
  # TEST-NET-1 address that no client has: the ACL never matches.
  never) acl='acl work_hours src 192.0.2.254/32' ;;
  *) usage ;;
esac

out=policy/generated/work_hours.conf
mkdir -p policy/generated
previous=''
[ ! -f "$out" ] || previous=$(cat "$out")
# Rewrite in place: a bind mount of ./policy keeps following this same file.
printf '%s\n' "# Generated by scripts/set-worktime.sh (mode: $mode). Do not edit." "$acl" > "$out"

if [ "$reload" = 1 ]; then
  if parse=$(docker compose exec -T squid squid -k parse 2>&1) \
     && ! printf '%s\n' "$parse" | grep -Eq 'FATAL|ERROR'; then
    docker compose exec -T squid squid -k reconfigure 2>/dev/null
  else
    [ -z "$previous" ] || printf '%s\n' "$previous" > "$out"
    printf '%s\n' "$parse" | grep -E 'FATAL|ERROR' >&2 || true
    echo "set-worktime: squid rejected the configuration, previous mode kept" >&2
    exit 1
  fi
fi
echo "WORK_HOURS_MODE=$mode"
