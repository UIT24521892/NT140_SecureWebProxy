#!/usr/bin/env bash
# Prepare untracked local state for the lab (spec §5.1, §5.5, §15; plan INF-1).
# Portable: bash 3.2/BSD (macOS) and bash 5/GNU (Linux).
set -euo pipefail

cd "$(dirname "$0")/.."

mkdir -p logs/squid captures results policy/lists/feeds policy/generated certs

if [ ! -f .env ]; then
  cp .env.example .env
  echo "init: created .env from .env.example"
fi

env_get() {
  # Print the value of KEY from .env, or the default given as $2.
  local value
  value=$(grep -E "^$1=" .env | tail -n 1 | cut -d= -f2- || true)
  if [ -n "$value" ]; then printf '%s\n' "$value"; else printf '%s\n' "$2"; fi
}

# Squid aborts on missing ACL files, so feed files must exist even when empty (spec §5.1).
for name in phishing malware threat_ips ut1_gambling ut1_games ut1_social_networks ut1_phishing ut1_malware; do
  feed="policy/lists/feeds/$name.txt"
  if [ ! -f "$feed" ]; then
    : > "$feed"
    echo "init: created empty $feed"
  fi
done

# ./policy is mounted read-only into squid, so the work_hours ACL is generated here (spec §5.5).
work_hours="policy/generated/work_hours.conf"
if [ ! -f "$work_hours" ]; then
  if [ -x scripts/set-worktime.sh ]; then
    scripts/set-worktime.sh --no-reload "$(env_get WORK_HOURS_MODE real)"
  else
    printf '%s\n' "# Generated by scripts/init.sh (mode: real). Change with: make worktime MODE=..." \
      "acl work_hours time MTWHF 08:00-17:00" > "$work_hours"
    echo "init: created $work_hours (mode real)"
  fi
fi

if [ -x scripts/gen-certs.sh ]; then
  scripts/gen-certs.sh
else
  echo "init: skip certificates, scripts/gen-certs.sh not implemented yet (TLS-1)"
fi

echo "init: done"
